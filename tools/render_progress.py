"""Implementation-progress validation and root TODO rendering; no file writes on import."""
from render_agent_backlogs import agent_backlogs_md, assignments, validate_assignments


def cell(value):
    return str(value).replace('|', '\\|').replace('\n', ' ')


def progress_counts(plan):
    return {status: sum(w['progress']['status'] == status for w in plan['work_packages'])
            for status in ('completed', 'partial', 'not-started')}


def evidence_links(paths, prefix=''):
    return ', '.join(f'[{path}]({prefix}{path})' for path in paths) or '-'


def validate_progress(root, plan, requirements, statuses, tests_by_requirement, owners_by_requirement):
    errors = validate_assignments(plan)
    packages = {w['id']: w for w in plan['work_packages']}
    for ident, w in packages.items():
        p = w.get('progress', {})
        status = p.get('status')
        if status not in {'completed', 'partial', 'not-started'}:
            errors.append(f'{ident}: missing or invalid progress status')
        done = p.get('completed_deliverables', [])
        if len(done) != len(set(done)) or not set(done) <= set(w['deliverables']):
            errors.append(f'{ident}: completed deliverables must be unique declared deliverables')
        if status == 'completed':
            if set(done) != set(w['deliverables']) or p.get('remaining_tasks'):
                errors.append(f'{ident}: completed work package has unfinished deliverables or remaining gates')
            for test in w['tests']:
                if statuses.get(test, {}).get('status') != 'automated':
                    errors.append(f'{ident}: completed work package requires automated acceptance test {test}')
        if status in {'completed', 'partial'} and (not p.get('implemented') or not p.get('evidence')):
            errors.append(f'{ident}: implementation claims need a concrete summary and evidence')
        if status == 'not-started' and (done or p.get('implemented')):
            errors.append(f'{ident}: not-started work package cannot claim completed implementation')
        for path in p.get('evidence', []):
            if not (root / path).is_file():
                errors.append(f'{ident}: evidence file does not exist: {path}')
    for rid, p in plan.get('requirement_progress', {}).items():
        if rid not in requirements:
            errors.append(f'unknown requirement progress {rid}')
        if p.get('status') not in {'partial', 'implemented'} or not p.get('summary'):
            errors.append(f'{rid}: invalid requirement progress')
        if not p.get('implemented_by') or not p.get('evidence'):
            errors.append(f'{rid}: requirement coverage needs an implementation owner and evidence')
        for owner in p.get('implemented_by', []):
            if owner not in packages or packages[owner]['type'] == 'spike':
                errors.append(f'{rid}: product coverage must refer to a product work package: {owner}')
        for path in p.get('evidence', []):
            if not (root / path).is_file():
                errors.append(f'{rid}: evidence file does not exist: {path}')
        if p.get('status') == 'implemented':
            if any(statuses.get(test, {}).get('status') != 'automated'
                   for test in tests_by_requirement.get(rid, [])):
                errors.append(f'{rid}: implemented requirement has incomplete acceptance coverage')
            if any(packages[owner]['progress']['status'] != 'completed'
                   for owner in owners_by_requirement.get(rid, []) if packages[owner]['type'] != 'spike'):
                errors.append(f'{rid}: implemented requirement has unfinished product work packages')
    for owner in plan['meta']['progress_review']['next_work']:
        if owner not in packages or packages[owner]['progress']['status'] == 'completed':
            errors.append(f'next work must be an unfinished work package: {owner}')
    for decision in plan.get('decisions', []):
        if decision['owner'] not in packages or decision['status'] not in {'open', 'decided'}:
            errors.append(f"{decision['id']}: invalid decision status or owner")
    return errors


def todo_md(plan, requirements, statuses, tests, tests_by_requirement, owners_by_requirement, test_owners, deferred):
    packages = {w['id']: w for w in plan['work_packages']}
    counts = progress_counts(plan)
    automated = sum(statuses.get(t['id'], {}).get('status') == 'automated' for t in tests)
    reviewed = plan['meta']['progress_review']
    out = ['# TODO', '', f"Last reviewed: {reviewed['date']} · baseline commit `{reviewed['baseline_commit']}`.", '',
           'Generated by `tools/render_requirements.py` from [work-packages.json](docs/plan/work-packages.json), '
           '[requirements.json](docs/requirements/requirements.json) and [test-status.json](docs/requirements/test-status.json). '
           'Edit those sources and regenerate; CI rejects stale tracking.', '',
           f"{len(packages)} work packages: **{counts['completed']} completed**, **{counts['partial']} partial**, "
           f"**{counts['not-started']} not started**. Acceptance: **{automated}/{len(tests)} automated**.", '',
           'A checked deliverable records implemented scope. A work package closes only when its remaining gates and '
           'owned acceptance tests are complete. Research completion records findings; it does not establish a product feature. '
           'Requirement coverage remains partial until the complete requirement is evidenced.', '']
    out += agent_backlogs_md(plan)
    owned = assignments(plan)
    out += ['',
            '## Requirement coverage', '',
            'All requirements are listed below. `partial` means a concrete capability is implemented; '
            '`planned` means no product coverage is claimed; `deferred` retains an explicit revisit condition. '
            'Automated-test counts describe test coverage, not complete requirement closure.', '',
            '| Requirement | Coverage | Automated acceptance tests | Work packages / disposition |', '|---|---|---|---|']
    for rid, requirement in requirements.items():
        p = plan.get('requirement_progress', {}).get(rid)
        status = p['status'] if p else ('deferred' if rid in deferred else 'planned')
        relevant = tests_by_requirement.get(rid, [])
        n = sum(statuses.get(t, {}).get('status') == 'automated' for t in relevant)
        coverage = f'{n}/{len(relevant)}' if relevant else 'Evidence review; no dedicated acceptance test'
        owner = ', '.join(owners_by_requirement.get(rid, [])) or 'Deferred; see revisit conditions'
        out.append(f"| {rid} {cell(requirement['title'])} | {status} | {coverage} | {owner} |")
    for phase in plan['phases']:
        out += ['', f"## Phase {phase['id']}: {phase['name']}", '', f"Milestone: {phase['milestone']}."]
        for w in plan['work_packages']:
            if w['phase'] != phase['id']:
                continue
            p = w['progress']
            out += ['', f"### {w['id']} {w['title']} — {p['status']}", '',
                    'Requirements: ' + (', '.join(w['requirements']) or 'Build support') + '. '
                    'Owned acceptance tests: ' + (', '.join(w['tests']) or 'Component/build verification') + '. '
                    'Start dependencies: ' + (', '.join(w['depends_on']) or 'None') + '.', '']
            if w['id'] in owned:
                task = owned[w['id']]
                out += [f"Implementation owner: **{task['owner']}**; reviewer: **{task['reviewer']}**; "
                        f"backlog: {task['ticket']}. Shared paths follow the exclusive write areas above.", '']
            out += [f"- [{'x' if text in p['completed_deliverables'] else ' '}] {text}" for text in w['deliverables']]
            if p['status'] == 'partial':
                out += ['', 'Implemented scope:', ''] + [f'- {text}' for text in p['implemented']]
            if p.get('scope_note'):
                out += ['', p['scope_note']]
            if p['remaining_tasks']:
                out += ['', 'Additional closure/integration tasks:', ''] + [f'- [ ] {text}' for text in p['remaining_tasks']]
            if w['tests']:
                out += ['', 'Acceptance gates:', '']
            for test in w['tests']:
                done = statuses.get(test, {}).get('status') == 'automated'
                out.append(f"- [{'x' if done else ' '}] {test}: " + ('automated' if done else 'implement, run in CI and record passing evidence'))
            if p['evidence']:
                out += ['', 'Evidence: ' + evidence_links(p['evidence'])]
    out += ['', '## Acceptance-test tracking', '', '| Test | Scenario / expected behavior | Owner | Status |', '|---|---|---|---|']
    for test in tests:
        status = statuses.get(test['id'], {}).get('status', 'not-started')
        out.append(f"| {test['id']} | {test['scenario']}: {cell(test['description'])} | {', '.join(test_owners[test['id']])} | {status} |")
    out += ['', '## Decisions and conditional follow-ups', '']
    for decision in plan.get('decisions', []):
        out.append(f"- [{'x' if decision['status'] == 'decided' else ' '}] **{decision['id']} {decision['title']}** "
                   f"({decision['owner']}): {decision['decision']}")
    out += ['', 'D-8 follow-up remains open in [issue #26](https://github.com/bassemZohdy/open-workflow-agentic/issues/26). '
            'The D-9 Vault integration is conditional work under WP-102; a recorded decision does not complete its integration test.', '',
            '## Deferred requirements', '', '| Requirements | Reason | Revisit when |', '|---|---|---|']
    out += [f"| {', '.join(d['ids'])} | {cell(d['reason'])} | {cell(d['revisit'])} |" for d in plan['deferred']]
    out += ['', '## Definition of done', '',
            'For each unfinished package: implement its deliverables, test failure/denial/timeout/crash/duplicate behavior, '
            'maintain identity/policy/audit boundaries, document safe defaults, run the required checks, update its evidence '
            'and acceptance records, then regenerate this file and the plan. Add delivered changes to [CHANGELOG.md](CHANGELOG.md).', '']
    return '\n'.join(out)
