#!/usr/bin/env python3
"""Render docs/requirements/*.md from docs/requirements/requirements.json (the single source of truth).

Usage: python3 tools/render_requirements.py [--check]
  --check  fail if the generated Markdown differs from what is committed.
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DIR = ROOT / "docs" / "requirements"
D = json.loads((DIR / "requirements.json").read_text(encoding="utf-8"))
STATUS = json.loads((DIR / "test-status.json").read_text(encoding="utf-8"))

REQ = {r["id"]: r for k in ("mandatory", "high", "optional") for r in D[k]}
TESTS = [dict(t, scenario=s["id"], scenario_title=s["title"]) for s in D["scenarios"] for t in s["tests"]]
BY_REQ = {}
for t in TESTS:
    for rid in t["verifies"]:
        BY_REQ.setdefault(rid, []).append(t["id"])


def cell(x):
    return str(x).replace("|", "\\|").replace("\n", " ")


def requirements_md():
    m = D["meta"]
    o = ["# Requirements", "",
         f"**Version:** {m['version']} · **Date:** {m['date']}  ",
         f"**Status:** {m['status']}  ", f"**Note:** {m['note']}", "",
         "Source of truth: [`requirements.json`](requirements.json). This file is generated by "
         "`tools/render_requirements.py`; edit the JSON, not this file.", "",
         f"{len(D['mandatory'])} Mandatory (M), {len(D['high'])} High (H), {len(D['optional'])} Optional (O); "
         f"{len(D['scenarios'])} scenarios, {len(TESTS)} test cases. See [test-cases.md](test-cases.md) and "
         "[traceability.md](traceability.md).", "",
         "## Principles", ""]
    o += [f"{i}. {p}" for i, p in enumerate(D["principles"], 1)]
    for key, title, intro in (
            ("mandatory", "Mandatory requirements", "A solution that fails a Mandatory requirement does not qualify."),
            ("high", "High-priority requirements", "Expected for a production platform; a gap needs a documented mitigation."),
            ("optional", "Optional requirements", "Valuable when enabled; constraints apply only when the capability is on.")):
        o += ["", f"## {title}", "", intro, "",
              "| ID | Title | Requirement | Scenarios | Verified by |", "|---|---|---|---|---|"]
        for r in D[key]:
            o.append("| %s | %s | %s | %s | %s |" % (
                r["id"], cell(r["title"]), cell(r["requirement"]),
                ", ".join(r.get("scenarios", [])) or "-", ", ".join(BY_REQ.get(r["id"], [])) or "-"))
    o += ["", "## Deployment profiles", "",
          "Profiles switch extra requirements on for specific deployments.", "",
          "| ID | Profile | Effect | Activated when |", "|---|---|---|---|"]
    o += ["| %s | %s | %s | %s |" % (p["id"], cell(p["name"]), cell(p["effect"]), cell(p["activation"])) for p in D["profiles"]]
    o += ["", "## Design decisions", "", "| ID | Topic | Decision | Status |", "|---|---|---|---|"]
    o += ["| %s | %s | %s | %s |" % (x["id"], cell(x["topic"]), cell(x["decision"]), x["status"]) for x in D["decisions"]]
    o += ["", "## References", "", "| ID | Title | Why it matters |", "|---|---|---|"]
    o += ["| %s | [%s](%s) | %s |" % (r["id"], cell(r["title"]), r["url"], cell(r["why"])) for r in D["references"]]
    return "\n".join(o) + "\n"


def tests_md():
    o = ["# Test cases", "",
         f"{len(TESTS)} acceptance tests in {len(D['scenarios'])} reference scenarios. Each test lists the requirements it verifies. "
         "Generated from [`requirements.json`](requirements/requirements.json); implementation status comes from "
         "[`test-status.json`](requirements/test-status.json).", ""]
    return o


def tests_md_full():
    o = ["# Test cases", "",
         f"{len(TESTS)} acceptance tests in {len(D['scenarios'])} reference scenarios. Each test lists the requirements it verifies.  ",
         "Generated by `tools/render_requirements.py` from [`requirements.json`](requirements.json); "
         "status comes from [`test-status.json`](test-status.json).", "",
         "Status values: `not-started`, `planned`, `partial`, `automated`.", ""]
    for s in D["scenarios"]:
        o += [f"## {s['id']} · {s['title']}", "", s["purpose"], "",
              "| Test | Description | Verifies | Status | Automated in |", "|---|---|---|---|---|"]
        for t in s["tests"]:
            st = STATUS.get(t["id"], {"status": "not-started", "where": ""})
            o.append("| %s | %s | %s | %s | %s |" % (t["id"], cell(t["description"]), ", ".join(t["verifies"]), st["status"], cell(st["where"]) or "-"))
        o.append("")
    return "\n".join(o)


def trace_md():
    o = ["# Traceability", "",
         "Requirement to test coverage and implementation status. Generated; do not edit.", "",
         "## Coverage summary", ""]
    counts = {}
    for t in TESTS:
        s = STATUS.get(t["id"], {}).get("status", "not-started")
        counts[s] = counts.get(s, 0) + 1
    o += ["| Status | Tests |", "|---|---:|"] + [f"| {k} | {v} |" for k, v in sorted(counts.items())]
    uncovered = [rid for rid in REQ if rid not in BY_REQ]
    o += ["", "## Requirement coverage", "",
          "| Requirement | Level | Tests | Best test status |", "|---|---|---|---|"]
    rank = {"automated": 3, "partial": 2, "planned": 1, "not-started": 0}
    for rid, r in REQ.items():
        ts = BY_REQ.get(rid, [])
        best = max((STATUS.get(t, {}).get("status", "not-started") for t in ts), key=lambda x: rank[x], default="no test")
        o.append("| %s %s | %s | %s | %s |" % (rid, cell(r["title"]), {"M": "Mandatory", "H": "High", "O": "Optional"}[rid[0]], ", ".join(ts) or "-", best))
    o += ["", "## Requirements without a dedicated acceptance test", "",
          ", ".join(uncovered) if uncovered else "None.", "",
          "Requirements without a test are not untested by intent: High and Optional items are normally verified "
          "through design review or the evidence listed in the requirement itself."]
    return "\n".join(o) + "\n"


OUT = {DIR / "README.md": requirements_md(), DIR.parent / "test-cases.md": tests_md_full() + "\n",
       DIR.parent / "traceability.md": trace_md()}
if "--check" in sys.argv:
    bad = [str(p) for p, c in OUT.items() if not p.exists() or p.read_text(encoding="utf-8") != c]
    if bad:
        sys.exit("out of date: " + ", ".join(bad))
    print("requirements docs up to date")
else:
    for p, c in OUT.items():
        p.write_text(c, encoding="utf-8")
        print("wrote", p.relative_to(ROOT))
